from __future__ import annotations

import hashlib
import json
from typing import Any


JsonObject = dict[str, Any]


def fingerprint(value: Any) -> str:
    canonical = json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(canonical).hexdigest()
